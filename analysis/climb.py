"""The hill-climb table: TPR and TNR on dev for every step, from the runs on the `data` branch.

  git fetch origin data
  python analysis/climb.py

Reads paper/climb.json (one entry per step, in order, including steps that
made things worse) and writes paper/climb_table.md and paper/climb.json's
companion paper/climb_results.json.
"""

import json
import os
import subprocess
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)
from analysis.rates import rate_ci  # noqa: E402
from judge.estimate import rates  # noqa: E402


def git_show(path, ref="data"):
    return subprocess.run(["git", "-C", ROOT, "show", f"{ref}:{path}"], capture_output=True, text=True,
                          check=True).stdout


def main():
    plan = json.load(open(os.path.join(ROOT, "paper", "climb.json")))
    t = plan["threshold"]
    results = []
    for s in plan["steps"]:
        m = json.loads(git_show(f"runs/{s['run']}/manifest.json"))
        assert m["variant"] == s["variant"] and m["split"] == plan["split"] and m["dataset"] == plan["dataset"], s
        rows = [json.loads(l) for l in git_show(f"runs/{s['run']}/judgments.jsonl").splitlines() if l.strip()]
        rows = [r for r in rows if r["call"] == 1 and r["noul"] is not None]
        r = rates([x["label"] for x in rows], [int(x["noul"] >= t) for x in rows])
        tpr_ci, tnr_ci = rate_ci(rows, t)
        results.append({**s, "model": m["model"], "fingerprint": m["fingerprint"], "n": r["n"],
                        "tp": r["tp"], "fn": r["fn"], "fp": r["fp"], "tn": r["tn"],
                        "tpr": r["tpr"], "tnr": r["tnr"], "tpr_ci": tpr_ci, "tnr_ci": tnr_ci,
                        "spend_usd": m.get("spend_usd")})
    json.dump(results, open(os.path.join(ROOT, "paper", "climb_results.json"), "w"), indent=1)
    f = lambda v, c: f"{v:.2f} [{c[0]:.2f}, {c[1]:.2f}]"
    lines = [f"| Step | Change | Model | TPR | TNR | False passes | False fails |",
             "|---|---|---|---|---|---|---|"]
    for r in results:
        lines.append(f"| {r['step']} | {r['change']} | {r['model']} | {f(r['tpr'], r['tpr_ci'])} | "
                     f"{f(r['tnr'], r['tnr_ci'])} | {r['fp']} | {r['fn']} |")
    lines += ["", f"Dev split: {results[0]['n']} items. First call, threshold {t}. "
              "95% intervals resample tickets. Generated by analysis/climb.py."]
    open(os.path.join(ROOT, "paper", "climb_table.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
